type GridName = keyof typeof GRIDS;
export type IconName = GridName | 'down' | 'left' | 'right' | 'redo';

function parse(grid: string): boolean[][] {
  return grid
    .trim()
    .split('\n')
    .map((row) => row.trim().padEnd(12, '.').slice(0, 12).split('').map((c) => c === '#'));
}

const rotateCW = (g: boolean[][]) => g[0].map((_, x) => g.map((row) => row[x]).reverse());
const flipH = (g: boolean[][]) => g.map((row) => [...row].reverse());
const flipV = (g: boolean[][]) => [...g].reverse();

const PARSED: Record<IconName, boolean[][]> = (() => {
  const out = {} as Record<IconName, boolean[][]>;
  for (const [name, grid] of Object.entries(GRIDS)) out[name as GridName] = parse(grid);
  out.down = flipV(out.up);
  out.right = rotateCW(out.up);
  out.left = flipH(out.right);
  out.redo = flipH(out.undo);
  return out;
})();

/** Merges horizontal runs into single rects to keep the SVG small. */
function toRects(g: boolean[][]): string {
  let d = '';
  g.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (!row[x]) {
        x++;
        continue;
      }
      const start = x;
      while (x < row.length && row[x]) x++;
      d += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(Object.entries(PARSED).map(([k, g]) => [k, toRects(g)])) as Record<IconName, string>;

export function Icon({ name, size = 18 }: { name: IconName; size?: number }) {
  return (
    <svg
      className="icon"
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden="true"
      fill="currentColor"
    >
      <path d={PATHS[name]} />
    </svg>
  );
}
